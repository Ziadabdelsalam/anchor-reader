    # Welcome to Anchor

    This is a short tour. Press **Space** to move to the next bit. That's the only key you really need.

    ## One bit at a time

    Notice how only one small piece of text is bright, and everything around it fades back. Long documents feel overwhelming partly because your eyes have too much to choose from. Lines above and below crowd the line you're on, and the whole page starts to blur together.

    Here, you only ever face a sentence or two. When you're done with it, press Space. If you want to go back, press Shift and Space together, or the left arrow.

    You can change how big each bit is in the **Aa** menu at the top of the window: one sentence, about two sentences, about four, or a whole paragraph. Smaller bites are easier to start on a hard day.

    If you'd like to see more of the surrounding text, there's a slider for that too. Some people like the page almost fully hidden; others like a faint outline of what's coming.

    ## Make the text comfortable

    Small, cramped text is genuinely harder to read. It's not just you. In eye-tracking studies, bigger text and wider letter spacing made people read faster, with or without dyslexia.

    Press **Command and Plus** to make the text bigger, or pinch on your trackpad. Open the **Aa** menu to change the font, the spacing between letters and words, the line width, and the colors.

    The **Reading comfort setup**, in the Reading menu, times you reading a few short passages in different fonts and tells you which one you read fastest in. People differ a lot here. The fastest font for one person can be one of the slowest for someone else.

    ## Short sprints, real breaks

    The timer at the bottom right counts down a short sprint. It starts at five minutes, because starting small is how you build up.

    When time is up, Anchor doesn't cut you off mid-sentence. It waits until you finish the bit you're on, then gives you a short break with the text hidden. Look away from the screen, stretch, get some water.

    If you're in the zone when the sprint ends, click the timer and add a couple of minutes. But it's usually better to stop while it still feels easy. That makes the next sprint easier to start.

    The timer also pauses when you switch to another app, and when you come back, Anchor shows you exactly where you were.

    ## The zoned-out key

    Everyone's mind wanders while reading. The trick is noticing it sooner. When you realize you've read a few lines without taking anything in, press **D**.

    Anchor steps you back one bit, no judgement. Over time, you'll catch yourself drifting earlier. That noticing is the real skill, and it gets stronger with practice.

    If you've been staring at one bit for much longer than your usual pace, a small "still with me?" appears at the bottom. Just press Space to carry on.

    ## Quick recall

    At the end of a section, Anchor asks you to sum it up in one sentence. You can type it, or just say it in your head.

    This is the most important feature in the app. Researchers at Harvard found that short recall questions between parts of a lecture cut mind-wandering roughly in half and helped people remember much more. Pulling an idea back out of memory is what makes it stick.

    Your answers collect in the notes panel (press **N**), and you can export them as Markdown. They make a great summary of whatever you read.

    ## Listening along

    Press **R** to have the current bit read aloud, with each word lighting up as it's spoken. Anchor moves to the next bit on its own when the voice finishes.

    Reading and listening together can make dense text much easier to follow, especially on tired days. You can choose a voice and speed in Settings. The "Enhanced" and "Premium" voices sound much more natural, and you can download them for free in System Settings.

    ## A few more keys

    | Key | What it does |
    |:---:|---|
    | **O** | Opens the map of the document, so you can see its sections and jump around |
    | **Z** | Hides everything except the text. Escape brings the controls back |
    | **F** | Full screen |
    | **B** | Starts a break right now |

    Tables like this one always fit the window. Long tables arrive a few rows at a time with the header repeated, and very wide ones turn into cards, one per row, so nothing is ever cut off. If a bit is ever taller than the window, Space shows the rest of it before moving on.

    You can also click any bit of text to jump straight to it.

    ## You're ready

    Open any Markdown, PDF, Word, RTF, HTML or plain text file with **Command O**, or drag it into the window. Anchor remembers where you stopped in every document.

    Before you start, put your phone in another room. A study at the University of Texas found that just having your phone on the desk, even face-down, uses up some of your attention.

    That's it. One small bit at a time.
